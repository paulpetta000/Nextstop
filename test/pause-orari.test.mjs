import { test } from 'node:test';
import assert from 'node:assert/strict';
import { calcolaGiorno } from '../src/lib/itinerari/calcolo.ts';
import { conPause } from '../src/lib/itinerari/pause.ts';
const scenari=['feriale','sabato','sabato-pomeriggio','domenica','festivo','piedi'];
function citta(){const mat=v=>Object.fromEntries(scenari.map(s=>[s,[0,v,v,0]]));return {tappe:['a','b'].map((id,p)=>({id,p,tipo:'citta',durata:30,chiuso:[],reversibile:false})),tempi:{n:2,min:mat(10),metri:mat(500),mezzi:mat('')},linee:{},zone:{}};}
const viaggio=(g={},data='2026-10-09')=>({id:'viaggio0',nome:'Prova',data,giorni:[{inizio:600,fine:1140,tappe:['a','b'],pause:[{quale:'caffe',min:60,dopo:'a'}],...g}],creato:1,modificato:1});
const giornata=(C,x,m=0,ora)=>conPause(C,x.giorni[0],calcolaGiorno(C,x,0,ora),m,{data:x.data,piedi:x.piedi});
function bus(partenze){const C=citta();C.tempi.min.feriale=[0,15,15,0];C.tempi.mezzi.feriale=['','B1','B1',''];C.vivo={dal:'20261009',al:'20261009',giorni:{'20261009':0},salite:[new Map()],viaggi:[new Map([['B1|salita|discesa',{min:10,partenze}]])],fermate:{salita:'Fermata A'},preferenza:5,candidati:[{seg:[5,'B1|salita|discesa',5],metri:300,mezzi:'B1'}],senza:{feriale:new Map([[1,{min:120,metri:5000,mezzi:''}]])},bus:{feriale:new Map([[1,[0]]])}};return C;}

test('pause e bus: la corsa va scelta dopo la pausa, con totali e distanze coerenti',()=>{const C=bus([640,740]),x=viaggio(),prima=structuredClone(x),r=giornata(C,x);
  const tr=r.voci.find(v=>v.tipo==='tratto');
  assert.equal(tr.corse[0].ora,740);
  assert.equal(tr.min,65);
  assert.equal(r.spostamenti,65);
  assert.equal(r.metri,300);
  assert.equal(r.voci.find(v=>v.id==='b').inizio,755);
  assert.deepEqual(x,prima);});
test('pause e bus: dopo l’ultima corsa passa al percorso senza bus',()=>{const r=giornata(bus([640]),viaggio());
  const tr=r.voci.find(v=>v.tipo==='tratto');
  assert.equal(tr.variante,'senza');
  assert.equal(tr.corse,undefined);
  assert.equal(tr.scartato.ora,-1);
  assert.equal(r.spostamenti,120);
  assert.equal(r.metri,5000);});
test('pause e locali: segnala la chiusura all’arrivo aggiornato',()=>{const C=citta();C.tappe[1].orari=Array.from({length:7},()=>[600,690]);
  const r=giornata(C,viaggio());
  assert.equal(r.voci.find(v=>v.id==='b').inizio,700);
  assert.ok(r.avvisi.some(a=>a.tipo==='chiusa-ora'&&a.id==='b'));
  assert.deepEqual(r.voci.find(v=>v.id==='b').chiusaOra,{});});
test('pause e locali: toglie l’avviso vecchio se la pausa porta dentro l’apertura',()=>{const C=citta();C.tappe[1].orari=Array.from({length:7},()=>[690,1000]);
  const r=giornata(C,viaggio());
  assert.equal(r.avvisi.some(a=>a.tipo==='chiusa-ora'),false);
  assert.equal(r.voci.find(v=>v.id==='b').chiusaOra,undefined);});
test('margini: controlla la chiusura per tutta la visita dopo lo spostamento',()=>{const C=citta();C.tappe[1].orari=Array.from({length:7},()=>[600,675]);
  const r=giornata(C,viaggio({pause:[]}),10);
  assert.equal(r.voci.find(v=>v.id==='b').fine,680);
  assert.deepEqual(r.avvisi.find(a=>a.tipo==='chiusa-ora'),{tipo:'chiusa-ora',id:'b',chiude:675});});
test('pause: ricalcola lo scenario quando supera il cambio dei mezzi del sabato',()=>{const C=citta();C.tempi.min['sabato-pomeriggio']=[0,40,40,0];
  const r=giornata(C,viaggio({inizio:840},'2026-10-10'));
  assert.equal(r.voci.find(v=>v.tipo==='tratto').scenario,'sabato-pomeriggio');
  assert.equal(r.spostamenti,40);});
test('pause ed evento: aggiorna ritardo, attesa e superamento del limite senza mutare il grezzo',()=>{const C=citta();C.evento={id:'b',p:1,inizio:660,durata:30,giorni:{'2026-10-09':{}},xy:[0,0]};
  const x=viaggio({fine:720}),base=calcolaGiorno(C,x,0),prima=structuredClone(base);
  const r=conPause(C,x.giorni[0],base,0,{data:x.data});
  const e=r.voci.find(v=>v.id==='b');
  assert.equal(e.ritardo,40);
  assert.equal(e.attesa,undefined);
  assert.equal(e.oltre,10);
  assert.deepEqual(r.avvisi.find(a=>a.tipo==='evento-tardi'),{tipo:'evento-tardi',ritardo:40});
  assert.deepEqual(base,prima);});
test('dal vivo: margine e prossima corsa rispettano l’ora attuale e le tappe fatte',()=>{const C=bus([640,740]),x=viaggio({fatte:['a'],pause:[]});
  const r=giornata(C,x,10,{data:x.data,ora:690});
  assert.equal(r.voci[0].fatta,true);
  assert.equal(r.voci.find(v=>v.tipo==='tratto').corse[0].ora,740);
  assert.equal(r.voci.find(v=>v.id==='b').inizio,765);});
